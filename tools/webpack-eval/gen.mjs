import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "app");
const ROOT = join(HERE, "..", "..");
const OUT = join(ROOT, "fixtures", "webpack-eval");

const DEVTOOLS = [
  "eval",
  "eval-cheap-source-map",
  "eval-cheap-module-source-map",
  "eval-source-map",
  "eval-nosources-source-map",
  "eval-nosources-cheap-source-map",
  "eval-nosources-cheap-module-source-map",
];

const VERSIONS = [
  { dir: "webpack4", package: "webpack-4" },
  { dir: "webpack5.24", package: "webpack-5.24" },
  { dir: "webpack5.75", package: "webpack-5.75" },
  { dir: "webpack5", package: "webpack" },
];

function cells(major) {
  const dev = DEVTOOLS.map((devtool) => ({
    name: `dev-${devtool}`,
    flags: `mode=development devtool=${devtool} target=node maxChunks=1`,
    config: { mode: "development", devtool, target: "node" },
  }));
  const extra = [
    {
      name: "dev-default",
      flags: "mode=development (devtool default) target=node maxChunks=1",
      config: { mode: "development", target: "node" },
    },
    {
      name: "prod-eval",
      flags: "mode=production devtool=eval target=node maxChunks=1",
      config: { mode: "production", devtool: "eval", target: "node" },
    },
  ];
  if (major === 5) {
    extra.push({
      name: "dev-web",
      flags: "mode=development (devtool default) target=web maxChunks=1",
      config: { mode: "development", target: "web" },
    });
  }
  return [...dev, ...extra];
}

function build(webpack, config, file) {
  const out = mkdtempSync(join(tmpdir(), "untwist-webpack-eval-"));
  const options = {
    ...config,
    context: APP,
    entry: "./index.js",
    node: false,
    output: { path: out, filename: "main.js", hashFunction: "sha256" },
    plugins: [new webpack.optimize.LimitChunkCountPlugin({ maxChunks: 1 })],
  };
  return new Promise((resolve, reject) => {
    webpack(options, (error, stats) => {
      if (error || stats.hasErrors()) {
        reject(error || new Error(stats.toString("errors-only")));
        return;
      }
      const text = readFileSync(join(out, "main.js"), "utf8").split(APP).join(".");
      rmSync(out, { recursive: true, force: true });
      writeFileSync(file, text);
      resolve(text);
    });
  });
}

const rows = [];
rmSync(OUT, { recursive: true, force: true });
for (const version of VERSIONS) {
  const webpack = require(version.package);
  const major = Number(webpack.version.split(".")[0]);
  mkdirSync(join(OUT, version.dir), { recursive: true });
  for (const cell of cells(major)) {
    const file = join(OUT, version.dir, `${cell.name}.js`);
    const text = await build(webpack, cell.config, file);
    const sha = createHash("sha256").update(text).digest("hex");
    rows.push([relative(OUT, file), `webpack@${webpack.version}`, "node", cell.flags, sha].join("\t"));
  }
}
const header = [
  `# node ${process.version} with NODE_OPTIONS=--openssl-legacy-provider (webpack 4 hashes with md4); generated by tools/webpack-eval/gen.mjs from tools/webpack-eval/app`,
  "# path\tbundler\tloader\tflags\tsha256",
];
writeFileSync(join(OUT, "MANIFEST"), [...header, ...rows, ""].join("\n"));
console.log(`${rows.length} fixtures`);
