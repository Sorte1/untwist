import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { transformSync } from "@babel/core";
import commonjs from "@rollup/plugin-commonjs";
import nodeResolve from "@rollup/plugin-node-resolve";
import { buildSync } from "esbuild";
import { rollup } from "rollup";
import { minify } from "terser";
import webpack from "webpack";

const ROOT = dirname(fileURLToPath(import.meta.url));
const REPO = join(ROOT, "..", "..");
const OUT = join(REPO, "fixtures", "modern");
const WORK = join(ROOT, "work");
const COREJS = JSON.parse(readFileSync(join(ROOT, "node_modules", "core-js", "package.json"), "utf8")).version;
const TARGETS = "ie 11";

const MODES = {
  usage: (source) => source,
  entry: (source) => `import "core-js/stable";\n${source}`,
};

const ENTRY_VARIANTS = new Set(["rollup-cjs", "rollup-cjs.terser", "esbuild.min"]);

function transpile(mode) {
  const source = MODES[mode](readFileSync(join(ROOT, "app.js"), "utf8"));
  const result = transformSync(source, {
    filename: join(WORK, `app.${mode}.js`),
    babelrc: false,
    configFile: false,
    sourceType: "module",
    presets: [
      [
        "@babel/preset-env",
        { targets: TARGETS, useBuiltIns: mode, corejs: COREJS.split(".").slice(0, 2).join("."), modules: false },
      ],
    ],
  });
  const file = join(WORK, `app.${mode}.js`);
  writeFileSync(file, result.code);
  return file;
}

async function rollupBuild(input, strictRequires) {
  const bundle = await rollup({
    input,
    onwarn: () => {},
    plugins: [nodeResolve({ rootDir: ROOT }), commonjs({ strictRequires })],
  });
  const { output } = await bundle.generate({ format: "iife" });
  await bundle.close();
  return output[0].code;
}

function webpackBuild(input, mode) {
  const compiler = webpack({
    mode,
    entry: input,
    context: ROOT,
    target: ["web", "es5"],
    devtool: false,
    resolve: { modules: [join(ROOT, "node_modules")] },
    optimization: { concatenateModules: false },
    output: { path: WORK, filename: `webpack.${mode}.out.js`, iife: true },
  });
  return new Promise((resolve, reject) => {
    compiler.run((error, stats) => {
      if (error || stats.hasErrors()) {
        reject(error ?? new Error(stats.toString("errors-only")));
        return;
      }
      compiler.close(() => resolve(readFileSync(join(WORK, `webpack.${mode}.out.js`), "utf8")));
    });
  });
}

function esbuildBuild(input, minified) {
  const result = buildSync({
    entryPoints: [input],
    bundle: true,
    write: false,
    format: "iife",
    target: "es5",
    supported: { arrow: false, "const-and-let": false },
    minify: minified,
    nodePaths: [join(ROOT, "node_modules")],
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

async function terse(code) {
  const result = await minify(code, { compress: true, mangle: true });
  return result.code;
}

const VARIANTS = [
  ["rollup-cjs", "rollup@4.66.0 @rollup/plugin-commonjs@29.0.3", "strictRequires=true format=iife", (input) => rollupBuild(input, true)],
  ["rollup-auto", "rollup@4.66.0 @rollup/plugin-commonjs@29.0.3", "strictRequires=auto format=iife", (input) => rollupBuild(input, "auto")],
  ["rollup-cjs.terser", "rollup@4.66.0 @rollup/plugin-commonjs@29.0.3 terser@5.51.2", "strictRequires=true format=iife, then terser compress+mangle", async (input) => terse(await rollupBuild(input, true))],
  ["webpack5.none", "webpack@5.112.2", "mode=none", (input) => webpackBuild(input, "none")],
  ["webpack5.prod", "webpack@5.112.2", "mode=production", (input) => webpackBuild(input, "production")],
  ["esbuild", "esbuild@0.28.2", "bundle format=iife target=es5", (input) => esbuildBuild(input, false)],
  ["esbuild.min", "esbuild@0.28.2", "bundle format=iife target=es5 minify", (input) => esbuildBuild(input, true)],
];

async function main() {
  rmSync(WORK, { recursive: true, force: true });
  mkdirSync(WORK, { recursive: true });
  mkdirSync(OUT, { recursive: true });
  const manifest = ["# file\ttools\tflags\tsha256 (generated by tools/modern-fixtures/build.mjs)"];
  for (const mode of Object.keys(MODES)) {
    const input = transpile(mode);
    for (const [name, tools, flags, build] of VARIANTS) {
      if (mode === "entry" && !ENTRY_VARIANTS.has(name)) continue;
      const code = await build(input);
      const file = `babel-${mode}.core-js-${COREJS}.${name}.js`;
      writeFileSync(join(OUT, file), code);
      const sha = createHash("sha256").update(code).digest("hex");
      const babel = `@babel/preset-env@7.29.14 useBuiltIns=${mode} corejs=${COREJS} targets="${TARGETS}"`;
      manifest.push(`${file}\t${babel} ${tools}\t${flags}\t${sha}`);
    }
  }
  writeFileSync(join(OUT, "MANIFEST"), `${manifest.join("\n")}\n`);
  rmSync(WORK, { recursive: true, force: true });
}

await main();
