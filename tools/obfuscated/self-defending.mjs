import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "../..");
const OUT = join(REPO, "fixtures/self-defending");
const SOURCES = join(HERE, "sources");
const require = createRequire(join(HERE, "package.json"));

const OBFUSCATORS = ["javascript-obfuscator-5.10", "javascript-obfuscator"];
const PROGRAMS = ["classes", "control", "functions", "mixed"];
const SEED = 5101;
const STRINGS = { stringArray: true, stringArrayThreshold: 1 };
const DICTIONARY = ["i", "ì", "í", "î", "ï"].flatMap((a) => ["i", "ì", "í", "î", "ï"].map((b) => `i${a}${b}`));

const COMBOS = {
  alone: {},
  cff: { controlFlowFlattening: true, controlFlowFlatteningThreshold: 1 },
  "dead-code": { deadCodeInjection: true, deadCodeInjectionThreshold: 1 },
  "dead-code-02": { deadCodeInjection: true, deadCodeInjectionThreshold: 0.2 },
  "cff-dead-code": { controlFlowFlattening: true, controlFlowFlatteningThreshold: 1, deadCodeInjection: true, deadCodeInjectionThreshold: 1 },
  "object-keys": { transformObjectKeys: true },
  "strings-none": { ...STRINGS, stringArrayEncoding: ["none"] },
  "strings-base64": { ...STRINGS, stringArrayEncoding: ["base64"], stringArrayRotate: true, stringArrayShuffle: true },
  "strings-rc4": { ...STRINGS, stringArrayEncoding: ["rc4"] },
  "wrappers-variable": { ...STRINGS, stringArrayWrappersCount: 2, stringArrayWrappersType: "variable" },
  "wrappers-rc4-function": {
    ...STRINGS, stringArrayEncoding: ["rc4"], stringArrayWrappersCount: 2, stringArrayWrappersType: "function",
    stringArrayWrappersChainedCalls: true, stringArrayWrappersParametersMaxCount: 4, stringArrayIndexShift: true,
  },
  "dead-code-rc4": { ...STRINGS, stringArrayEncoding: ["rc4"], deadCodeInjection: true, deadCodeInjectionThreshold: 1 },
  "names-mangled-shuffled": { identifierNamesGenerator: "mangled-shuffled" },
  "names-dictionary": { ...STRINGS, stringArrayEncoding: ["none"], identifierNamesGenerator: "dictionary", identifiersDictionary: DICTIONARY.flatMap((a) => DICTIONARY.map((b) => a + b.slice(1))) },
  heavy: {
    ...STRINGS, stringArrayEncoding: ["base64", "rc4"], stringArrayWrappersCount: 1, stringArrayRotate: true, stringArrayShuffle: true,
    controlFlowFlattening: true, controlFlowFlatteningThreshold: 0.5, deadCodeInjection: true, deadCodeInjectionThreshold: 0.2,
    transformObjectKeys: true, identifierNamesGenerator: "mangled-shuffled",
  },
  "heavy-full": {
    ...STRINGS, stringArrayEncoding: ["base64", "rc4"], stringArrayWrappersCount: 1, stringArrayRotate: true, stringArrayShuffle: true,
    controlFlowFlattening: true, controlFlowFlatteningThreshold: 1, deadCodeInjection: true, deadCodeInjectionThreshold: 1,
    transformObjectKeys: true, numbersToExpressions: true, splitStrings: true, unicodeEscapeSequence: true,
  },
};

const MINIFIED = ["dead-code", "cff-dead-code", "heavy"];
const terser = require("terser-5");

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const run = (file) => execFileSync(process.execPath, [file], { encoding: "utf8", timeout: 10000 });

function version(alias) {
  return JSON.parse(readFileSync(require.resolve(`${alias}/package.json`), "utf8")).version;
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, "expected"), { recursive: true });
const rows = [
  "# file\tcombo\tsource\tseed\tobfuscator\toptions\tsha256",
  `# generated by tools/obfuscated/self-defending.mjs with node ${process.version}; every row has selfDefending on; expected/<file>.stdout is node on the source`,
];
for (const alias of OBFUSCATORS) {
  const obfuscator = require(alias);
  const tag = `javascript-obfuscator@${version(alias)}`;
  for (const [combo, extra] of Object.entries(COMBOS)) {
    for (const program of PROGRAMS) {
      const sourcePath = join(SOURCES, `${program}.js`);
      const options = { seed: SEED, target: "node", selfDefending: true, ...extra };
      const code = obfuscator.obfuscate(readFileSync(sourcePath, "utf8"), options).getObfuscatedCode();
      const variants = [[combo, code, tag]];
      if (MINIFIED.includes(combo)) {
        const minified = (await terser.minify(code, { compress: { passes: 2 }, mangle: true })).code;
        variants.push([`${combo}-terser`, minified, `${tag}+terser@${version("terser-5")}`]);
      }
      for (const [name, text, tool] of variants) {
        const file = `${version(alias)}--${name}--${program}.js`;
        const path = join(OUT, file);
        writeFileSync(path, text);
        const want = run(sourcePath);
        if (run(path) !== want) throw new Error(`${file}: the obfuscated program prints something else`);
        writeFileSync(join(OUT, "expected", `${file}.stdout`), want);
        rows.push([file, name, `tools/obfuscated/sources/${program}.js`, SEED, tool, JSON.stringify(extra), sha256(text)].join("\t"));
      }
    }
  }
}
writeFileSync(join(OUT, "MANIFEST"), rows.join("\n") + "\n");
console.log(`${rows.length - 2} fixtures in ${OUT}`);
