import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "../..");
const OUT = join(REPO, "fixtures/obfuscated");
const WORK = join(HERE, "node_modules/.work");
const require = createRequire(join(HERE, "package.json"));
const JavaScriptObfuscator = require("javascript-obfuscator");

const STRINGS = {
  compact: true,
  stringArray: true,
  stringArrayThreshold: 1,
  stringArrayRotate: true,
  stringArrayShuffle: true,
  stringArrayEncoding: ["base64", "rc4"],
  stringArrayIndexesType: ["hexadecimal-number"],
  stringArrayWrappersCount: 1,
  selfDefending: true,
  target: "node",
};

const HEAVY = {
  ...STRINGS,
  renameGlobals: true,
  deadCodeInjection: true,
  deadCodeInjectionThreshold: 0.4,
  controlFlowFlattening: true,
  controlFlowFlatteningThreshold: 0.75,
};

const FIXTURES = [
  { name: "webpack4-strings.js", source: "webpack4", seed: 4101, options: STRINGS },
  { name: "webpack5-strings.js", source: "webpack5", seed: 5101, options: STRINGS },
  { name: "plain-strings.js", source: "plain", seed: 7101, options: STRINGS },
  { name: "webpack4-heavy.js", source: "webpack4", seed: 4202, options: HEAVY },
];

const version = (name) => JSON.parse(readFileSync(require.resolve(`${name}/package.json`), "utf8")).version;
const sha256 = (text) => createHash("sha256").update(text).digest("hex");

function compile(webpack, config) {
  return new Promise((done, fail) => {
    webpack(config, (error, stats) => {
      if (error || stats.hasErrors()) fail(error || new Error(stats.toString("errors-only")));
      else done();
    });
  });
}

function baseConfig(filename) {
  return {
    context: HERE,
    entry: "./app/index.js",
    target: "node",
    node: false,
    mode: "production",
    devtool: false,
    output: { path: WORK, filename, hashFunction: "sha256" },
  };
}

async function webpack4() {
  const TerserPlugin = require("terser-webpack-plugin");
  const minimizer = new TerserPlugin({ cache: false, parallel: false, extractComments: false });
  const config = baseConfig("webpack4.js");
  await compile(require("webpack"), { ...config, optimization: { minimizer: [minimizer] } });
  return readFileSync(join(WORK, "webpack4.js"), "utf8");
}

async function webpack5() {
  const config = baseConfig("webpack5.js");
  await compile(require("webpack5"), { ...config, optimization: { concatenateModules: false } });
  return readFileSync(join(WORK, "webpack5.js"), "utf8");
}

function runNode(file) {
  return execFileSync(process.execPath, ["--no-warnings", file], { cwd: dirname(file), encoding: "utf8", timeout: 30000 });
}

async function main() {
  mkdirSync(WORK, { recursive: true });
  mkdirSync(join(OUT, "expected"), { recursive: true });
  const expected = runNode(join(HERE, "app/index.js"));
  if (runNode(join(HERE, "plain/script.cjs")) !== expected) throw new Error("plain/script.cjs and app/index.js print different things");
  const sources = { webpack4: await webpack4(), webpack5: await webpack5(), plain: readFileSync(join(HERE, "plain/script.cjs"), "utf8") };
  for (const [name, code] of Object.entries(sources)) {
    const file = join(WORK, `${name}.cjs`);
    writeFileSync(file, code);
    if (runNode(file) !== expected) throw new Error(`the unobfuscated ${name} build prints other than the sources`);
  }
  const manifest = [
    "# file\tsource\tbundler\tobfuscator\tseed\toptions\tsha256",
    `# generated by tools/obfuscated/gen.mjs with node ${process.version}; expected/<file>.stdout is node on tools/obfuscated/app/index.js`,
  ];
  const bundlers = { webpack4: `webpack@${version("webpack")}`, webpack5: `webpack@${version("webpack5")}`, plain: "none" };
  for (const fixture of FIXTURES) {
    const options = { ...fixture.options, seed: fixture.seed };
    const code = `${JavaScriptObfuscator.obfuscate(sources[fixture.source], options).getObfuscatedCode()}\n`;
    if (code.includes(REPO) || code.includes(HERE)) throw new Error(`${fixture.name} embeds a local path`);
    const file = join(OUT, fixture.name);
    writeFileSync(file, code);
    const ran = runNode(file);
    if (ran !== expected) throw new Error(`${fixture.name} prints other than the sources:\n${ran}`);
    writeFileSync(join(OUT, "expected", `${fixture.name}.stdout`), expected);
    manifest.push([fixture.name, relative(REPO, join(HERE, fixture.source === "plain" ? "plain/script.cjs" : "app")), bundlers[fixture.source], `javascript-obfuscator@${version("javascript-obfuscator")}`, fixture.seed, JSON.stringify(fixture.options), sha256(code)].join("\t"));
  }
  writeFileSync(join(OUT, "MANIFEST"), `${manifest.join("\n")}\n`);
}

await main();
